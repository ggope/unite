export const LANGS = { en: 'English', hu: 'Magyar' } as const;
export type Lang = keyof typeof LANGS;
const DICTS: Record<Lang, Record<Key, string>> = { en, hu };

export type T = (key: Key, vars?: Record<string, string | number>) => string;
export function makeT(lang: Lang): T {
  const d = DICTS[lang] ?? en;
  return (key, vars) => {
    let s = d[key] ?? en[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
    return s;
  };
}
export const locale = (lang: Lang) => (lang === 'hu' ? 'hu-HU' : 'en-GB');
export const fmtN = (n: number, lang: Lang) => Number(n || 0).toLocaleString(lang === 'hu' ? 'hu-HU' : 'en-US');
export const pickLang = (cookie?: string | null, accept?: string | null): Lang =>
  cookie === 'hu' || cookie === 'en' ? cookie : /^\s*hu\b/i.test(accept ?? '') ? 'hu' : 'en';
